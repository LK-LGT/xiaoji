"""飞书消息意图识别 —— **分层路由**。

⚠️ **为什么不能只靠关键词**
----------------------------
最初的实现是「命中 7 个关键词 → ``performance_qa``，否则回提示卡」。
在真实使用里这会**大量漏判** —— 员工说的是口语：

    「我这个月分数怎么算出来的」   ← 缺「得分/评分/绩效/指标」→ 漏
    「我表现怎么样」                 ← 漏
    「上个月我拿了多少分」           ← 漏
    「我被扣了吗」                   ← 缺「扣分」→ 漏
    「咱部门这月整体如何」           ← 缺「部门统计」→ 漏

漏判的后果比「答不了」更糟：用户收到一张
「请发送 xxx」的提示卡 ⇒ **用户以为机器人坏了**。

⇒ 结论：**关键词只能用来识别「明确的写操作指令」**，
   不能用来当「是不是绩效问题」的判据。

⚠️ **分层路由**
--------------
    ① 写操作指令（取消 / 填月计划 / 考核填报）
       —— 这类话**表达固定、后果有副作用**，关键词足够可靠。
    ② 明确的绩效问法
       —— 命中领域词直接进问答，省一次模型往返。
    ③ **兜底：其余一切**
       —— 交给 L3 模型自己判断「这个问题我能不能答」。
       模型答不了时它自己会回「这个我不清楚」。

为什么 ③ 安全：
    - **权限不受影响**。真正的范围收敛在 ``qa_permission.resolve_scope``，
      那里按员工身份解析 ``allowed_tools``，与本模块无关。
      ⇒ 放宽识别**不等于**放宽数据可见性。
    - **只读**。问答链路不写任何业务数据。
    - **不会误触发写操作**。①②的指令类意图优先级更高，
      写操作永远不会被 ③ 抢走。

⚠️ **为什么写操作不放给模型判断**
--------------------------------
「帮我把方案填一下」和「填月计划」在模型看来是同一件事，
但填错对象（部门方案 vs 月计划）的后果是**写入错误的草稿**。
这类意图宁可漏（回提示卡），不可错。
"""

from __future__ import annotations

# ===========================================================================
# 意图常量
# ===========================================================================

#: 没命中任何明确意图 —— **交给模型兜底**，不是拒绝
INTENT_NONE = "none"

#: 取消当前操作
INTENT_CANCEL = "cancel"

#: 填月计划（写操作）
INTENT_MONTH_PLAN = "month_plan"

#: 绩效问答（只读）
INTENT_PERFORMANCE_QA = "performance_qa"

#: 填报表数据（写操作）—— BP-2 / P3
INTENT_MANUAL_METRIC = "manual_metric"

# ===========================================================================
# ① 写操作指令 —— 表达固定，关键词可靠
# ===========================================================================

#: 取消关键词
CANCEL_KEYWORDS: tuple[str, ...] = (
    "取消",
    "算了",
    "不填了",
    "不问了",
    "先不",
)

#: 填月计划关键词
MONTH_PLAN_KEYWORDS: tuple[str, ...] = (
    "填月计划",
    "填月度计划",
    "月计划",
    "月度计划",
    "写计划",
    "填表",
)

#: 填报表数据（完播率 / 留存率等人工指标）—— ★ BP-2 / P3
#:
#: ⚠️ **必须排在 ``MONTH_PLAN_KEYWORDS`` 之前判定**
#: 「填表」在月计划词表里，而「填报表数据」也含「填表」——
#: 若月计划先判，「填报表数据」会被当成「填月计划」⇒ 员工填了指标却进了月计划表单。
#: ⇒ 顺序：填报 → 月计划 → 绩效。
MANUAL_METRIC_KEYWORDS: tuple[str, ...] = (
    "填报表数据",
    "填数据",
    "报数据",
    "填指标",
    "填效果",
    "完播率",
    "留存率",
    "完播",
    "留存",
    "上报数据",
    "提交数据",
)

# ===========================================================================
# ② 绩效领域词 —— 只用来「快速通道」，漏了也不致命
# ===========================================================================

#: ⚠️ **这份词表不是「判据」，是「快捷方式」**。
#:
#: 命中 → 直接进问答，省一次模型往返。
#: 没命中 → 走 ③ 兜底，模型自己判断。
#:
#: ⇒ 所以**不需要**穷举所有说法，漏几个词没有后果。
#:    （早期版本把它当判据用，于是到处漏判 —— 那才是真正的 bug。）
#:
#: ⚠️ **别指望这份词表能覆盖口语** ——
#:    真实漏判过的：「我被扣了吗」（没「扣分」）、
#:    「我够格吗」（完全没覆盖）。
#:    补了这两个，又会有下一个漏的。
#:
#:    ⇒ 维护这条线的心态应该是：
#:    **漏一个补一个**（顺手），而不是**穷举**（做不到）。
#:    兜底兜住漏掉的那些。
PERFORMANCE_KEYWORDS: tuple[str, ...] = (
    # ── 分数与得分 ──
    "绩效",
    "评分",
    "得分",
    "分数",
    "考核分",
    "打分",
    "扣分",
    "减分",
    "加分",
    "考分",
    "多少分",
    "计分",
    "被扣",
    "扣了",
    "扣过",
    # ── 指标与达成 ──
    "指标",
    "达成",
    "完成度",
    "权重",
    "算分",
    "怎么算",
    "怎么算的",
    "怎么计算",
    "怎么得出的",
    "构成",
    "贡献",
    # ── 表现与评价 ──
    "表现",
    "评价",
    "评估",
    "怎么样",
    "如何",
    "考得",
    "评级",
    "等级",
    "档",
    "够格",
    "合格",
    "过线",
    "达标",
    # ── 部门与团队 ──
    "部门",
    "团队",
    "小组",
    "平均",
    "均分",
    "排名",
    # ── 时间与场景 ──
    "这个月",
    "上个月",
    "这个季度",
    "考核",
    "评估结果",
    "我的结果",
    "我的情况",
)


def detect_intent(text: str) -> str:
    """从员工消息里识别意图。

    ⚠️ **返回 ``none`` 不代表「拒绝」** —— 它代表「没命中明确意图」，
    应当走**模型兜底**（见 ``feishu_bot`` 的调用点）。

    这是**纯函数**，不碰数据库 —— 好测。

    ⚠️ **顺序很重要**：
    ① 取消 → ② 写操作（填报 → 月计划）→ ③ 绩效快捷通道。
    取消优先级最高（用户在填表中途说「算了」，
    不该被当成「我要填月计划」）。
    """
    if not text:
        return INTENT_NONE

    normalized = text.strip().lower()

    # ── ① 取消 ────────────────────────────────────────────
    if any(keyword in normalized for keyword in CANCEL_KEYWORDS):
        return INTENT_CANCEL

    # ── ② 写操作指令 ──────────────────────────────────────
    # ⚠️ **填报必须在月计划之前** —— 「填表」是月计划词表里的词，
    #    而「填报表数据」也含「填表」；顺序反了会把填报导进月计划表单。
    if any(keyword in normalized for keyword in MANUAL_METRIC_KEYWORDS):
        return INTENT_MANUAL_METRIC

    # ⚠️ 放在绩效关键词**之前** ——
    #    「填月计划时顺便看看我的绩效」必须走填月计划，不是问答。
    if any(keyword in normalized for keyword in MONTH_PLAN_KEYWORDS):
        return INTENT_MONTH_PLAN

    from .feishu_scheme import INTENT as SCHEME_INTENT
    from .feishu_scheme import KEYWORDS as SCHEME_KEYWORDS

    if any(keyword in normalized for keyword in SCHEME_KEYWORDS):
        return SCHEME_INTENT

    # ── ③ 绩效快捷通道 ────────────────────────────────────
    if any(keyword in normalized for keyword in PERFORMANCE_KEYWORDS):
        return INTENT_PERFORMANCE_QA

    # ── ④ 兜底：交给模型 ──────────────────────────────────
    return INTENT_NONE


def is_performance_related(text: str) -> bool:
    """这句话是否**可能**与绩效有关。

    ⚠️ 这是**宽松判断**，用于兜底路由的说明与日志，
    不是精确分类 —— 精确分类交给 L3 模型。
    """
    if not text:
        return False
    normalized = text.strip().lower()
    return any(keyword in normalized for keyword in PERFORMANCE_KEYWORDS)


